export const COLLEGES_DATA: string[] = COLLEGE_RECORDS.map((c) => c.name);

/**
 * Searches college database with query matching college name, city, or acronym
 */
export function findMatchingColleges(query: string, maxResults = 8): CollegeRecord[] {
  const clean = query.trim().toLowerCase();
  if (!clean) return COLLEGE_RECORDS.slice(0, maxResults);

  return COLLEGE_RECORDS.filter((col) => {
    return (
      col.name.toLowerCase().includes(clean) ||
      col.city.toLowerCase().includes(clean) ||
      (col.affiliation && col.affiliation.toLowerCase().includes(clean))
    );
  }).slice(0, maxResults);
}

/**
 * Retrieves exact or closest college record
 */
export function getCollegeRecord(collegeNameOrId: string): CollegeRecord | null {
  if (!collegeNameOrId) return null;
  const clean = collegeNameOrId.trim().toLowerCase();

  // Try exact ID match
  const byId = COLLEGE_RECORDS.find((c) => c.id.toLowerCase() === clean);
  if (byId) return byId;

  // Try exact Name match
  const byName = COLLEGE_RECORDS.find((c) => c.name.toLowerCase() === clean);
  if (byName) return byName;

  // Try partial name match
  const partial = COLLEGE_RECORDS.find((c) =>
    c.name.toLowerCase().includes(clean) || clean.includes(c.name.toLowerCase())
  );
  return partial || null;
}

/**
 * Safely format college attributes without inventing data
 * Returns "Information not configured" if absent
 */
export function formatCollegeDetail(value?: string | null): string {
  if (!value || !value.trim()) {
    return 'Information not configured';
  }
  return value.trim();
}
