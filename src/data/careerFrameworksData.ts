export type CareerDomain = typeof CAREER_DOMAINS[number];

// Helper to normalize domain for filtering
export function mapDomainToFilter(domain: string): CareerDomain {
  if (domain.includes('Software') || domain.includes('Development')) return 'Software';
  if (domain.includes('Data') || domain.includes('Analytics')) return 'Data';
  if (domain.includes('AI') || domain.includes('Machine Learning')) return 'AI & ML';
  if (domain.includes('Cyber') || domain.includes('Security')) return 'Cyber Security';
  if (domain.includes('Cloud') || domain.includes('Networking')) return 'Cloud & Networking';
  if (domain.includes('Design') || domain.includes('Creative')) return 'Design';
  if (domain.includes('Business') || domain.includes('Management')) return 'Business';
  if (domain.includes('Finance') || domain.includes('Commerce')) return 'Finance';
  if (domain.includes('Healthcare') || domain.includes('Bio')) return 'Healthcare';
  if (domain.includes('Engineering')) return 'Engineering';
  if (domain.includes('Science') || domain.includes('Research')) return 'Science & Research';
  if (domain.includes('Education')) return 'Education';
  return 'Software';
}

